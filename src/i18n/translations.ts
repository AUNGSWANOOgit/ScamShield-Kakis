export const DICTIONARIES = { en, zh } as const;

export function translate(lang: 'en' | 'zh', key: TranslationKey, vars?: Record<string, string | number>): string {
  let s: string = (lang === 'zh' ? zh[key] : undefined) ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}
